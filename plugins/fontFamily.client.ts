export default defineNuxtPlugin(() => {
	const userStore = useUserStore()
	const { applyFont } = useFontFamily()

	watch(
		() => userStore.user?.settings_object?.fontFamily,
		(font) => {
			if (font) applyFont(font)
		},
		{ immediate: true },
	)
})
